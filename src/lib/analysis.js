import { CATEGORY_MAP, DUPLICATE_COMPONENT_WEIGHTS, PRIORITY_BANDS } from './constants';
import { formatPercent } from './format';

/** Human labels for the four duplicate similarity components. */
export const DUPLICATE_COMPONENT_LABELS = {
  text: 'Text similarity',
  category: 'Category match',
  geo: 'Distance',
  time: 'Time gap',
};

/**
 * The stored score must equal the sum of the stored factors. The hazard
 * escalation and the 100-point cap are ordinary rows, so this holds for every
 * report, including the three seeded P0 hazards.
 *
 * @param {{factors?: Array<{points: number}>}|null} priority
 */
export function sumFactorPoints(priority) {
  return (priority?.factors ?? []).reduce(
    (total, factor) => total + Number(factor.points ?? 0),
    0,
  );
}

export function factorsMatchScore(priority) {
  if (!priority || !Number.isFinite(Number(priority.score))) return false;
  return sumFactorPoints(priority) === Number(priority.score);
}

/**
 * Raw component value, its frozen weight and the points it contributes to the
 * final similarity score.
 *
 * @param {{text?: number, category?: number, geo?: number, time?: number}} components
 */
export function duplicateContributions(components = {}) {
  return Object.entries(DUPLICATE_COMPONENT_WEIGHTS).map(([key, weight]) => {
    const raw = Math.max(0, Math.min(1, Number(components[key] ?? 0)));
    return {
      key,
      label: DUPLICATE_COMPONENT_LABELS[key] ?? key,
      weight,
      raw,
      points: Number((raw * weight).toFixed(3)),
    };
  });
}

export function bandLabel(band) {
  return PRIORITY_BANDS[band]?.label ?? band ?? 'Unscored';
}

/**
 * Plain-text summary used by the "Copy summary" button. It contains only
 * stored fields, so it can be pasted into a handover note without editing.
 *
 * @param {import('@/types').Report} report
 */
export function buildCopySummary(report) {
  if (!report) return '';

  const ai = report.ai ?? null;
  const category = CATEGORY_MAP[report.category] ?? CATEGORY_MAP.other;
  const lines = [
    `CivicPulse AI · ${report.referenceCode}`,
    report.title ? report.title : null,
    `Category: ${category.label}${ai ? ` (${formatPercent(ai.confidence, 0)} confidence)` : ''}`,
    `Priority: ${report.priorityScore ?? '—'}/100 · ${report.priorityBand ?? 'unscored'} (${bandLabel(report.priorityBand)})`,
    `Status: ${report.status}`,
    report.locationLabel ? `Location: ${report.locationLabel}` : null,
  ].filter(Boolean);

  if (ai?.summary) lines.push('', `Summary: ${ai.summary}`);

  if (ai?.priority?.factors?.length) {
    const drivers = ai.priority.factors
      .filter((factor) => Number(factor.points) > 0)
      .sort((a, b) => Number(b.points) - Number(a.points))
      .slice(0, 3)
      .map((factor) => `${factor.label} +${factor.points}`)
      .join(', ');
    if (drivers) lines.push(`Main factors: ${drivers}`);
  }

  if (ai?.duplicates?.length) {
    const strongest = ai.duplicates[0];
    lines.push(
      `Duplicate proposals: ${ai.duplicates.length} (strongest ${formatPercent(strongest.score, 0)} vs ${strongest.referenceCode})`,
    );
  }

  if (ai?.cluster) {
    lines.push(
      `Hotspot: ${ai.cluster.label} · ${ai.cluster.count} reports · ${ai.cluster.trend}`,
    );
  }

  lines.push('', 'Generated by rules-v1 — deterministic, offline, no image analysis.');
  return lines.join('\n');
}
