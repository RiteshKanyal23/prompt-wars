import { describe, expect, it } from 'vitest';
import {
  bandLabel,
  buildCopySummary,
  duplicateContributions,
  factorsMatchScore,
  sumFactorPoints,
} from '@/lib/analysis';
import { DUPLICATE_COMPONENT_WEIGHTS } from '@/lib/constants';

const priority = {
  score: 79,
  factors: [
    { code: 'base', points: 30 },
    { code: 'impact', points: 20 },
    { code: 'spread', points: 15 },
    { code: 'time', points: 9 },
    { code: 'cluster', points: 5 },
  ],
};

describe('priority arithmetic helpers', () => {
  it('sums the stored factor points', () => {
    expect(sumFactorPoints(priority)).toBe(79);
    expect(sumFactorPoints(null)).toBe(0);
    expect(sumFactorPoints({ factors: [{ points: '5' }, { points: 7 }] })).toBe(12);
  });

  it('detects whether the factors reconcile with the displayed score', () => {
    expect(factorsMatchScore(priority)).toBe(true);
    expect(factorsMatchScore({ ...priority, score: 80 })).toBe(false);
    expect(factorsMatchScore({ factors: priority.factors })).toBe(false);
    expect(factorsMatchScore(null)).toBe(false);
  });

  it('labels every priority band and falls back for unknown values', () => {
    expect(bandLabel('P0')).toBe('Critical');
    expect(bandLabel('P3')).toBe('Low');
    expect(bandLabel('P9')).toBe('P9');
    expect(bandLabel(undefined)).toBe('Unscored');
  });
});

describe('duplicateContributions', () => {
  it('returns one weighted row per component with points that add up', () => {
    const rows = duplicateContributions({ text: 0.9, category: 1, geo: 0.5, time: 0.25 });

    expect(rows.map((row) => row.key)).toEqual(Object.keys(DUPLICATE_COMPONENT_WEIGHTS));
    expect(rows.reduce((sum, row) => sum + row.weight, 0)).toBeCloseTo(1);
    expect(rows.reduce((sum, row) => sum + row.points, 0)).toBeCloseTo(0.9 * 0.55 + 0.2 + 0.5 * 0.15 + 0.25 * 0.1);
    expect(rows.find((row) => row.key === 'text')).toMatchObject({
      label: 'Text similarity',
      weight: 0.55,
      raw: 0.9,
      points: 0.495,
    });
  });

  it('clamps out-of-range and missing values', () => {
    const rows = duplicateContributions({ text: 2, category: -1 });
    expect(rows.find((row) => row.key === 'text').raw).toBe(1);
    expect(rows.find((row) => row.key === 'category').raw).toBe(0);
    expect(rows.find((row) => row.key === 'geo').raw).toBe(0);
  });
});

describe('buildCopySummary', () => {
  const report = {
    referenceCode: 'CP-7K2M9Q',
    title: 'Knee-deep water outside Sunrise School',
    category: 'water',
    priorityScore: 79,
    priorityBand: 'P1',
    status: 'triaged',
    locationLabel: 'School gate, 4th Cross, Sector 12',
    ai: {
      confidence: 0.98,
      summary: 'Knee-deep water is blocking the school gate.',
      priority: {
        score: 79,
        factors: [
          { label: 'Impact', points: 20 },
          { label: 'Cluster', points: 5 },
          { label: 'Base severity', points: 30 },
        ],
      },
      duplicates: [{ score: 0.91, referenceCode: 'CP-AAAAAA' }],
      cluster: { label: 'Sector 12', count: 7, trend: 'rising' },
    },
  };

  it('contains only stored fields, in a stable order', () => {
    const text = buildCopySummary(report);

    expect(text).toContain('CivicPulse AI · CP-7K2M9Q');
    expect(text).toContain('Priority: 79/100 · P1 (High)');
    expect(text).toContain('Summary: Knee-deep water is blocking the school gate.');
    expect(text).toContain('Main factors: Base severity +30, Impact +20, Cluster +5');
    expect(text).toContain('Duplicate proposals: 1 (strongest 91% vs CP-AAAAAA)');
    expect(text).toContain('Hotspot: Sector 12 · 7 reports · rising');
    expect(text.trim().endsWith('Generated by rules-v1 — deterministic, offline, no image analysis.')).toBe(
      true,
    );
  });

  it('degrades cleanly when analysis is missing', () => {
    const text = buildCopySummary({ ...report, ai: null });
    expect(text).toContain('Priority: 79/100');
    expect(text).not.toContain('Summary:');
    expect(buildCopySummary(null)).toBe('');
  });
});
